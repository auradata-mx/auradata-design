const HEADER = '/* Generated by @auradata/tokens. Do not edit: change src/tokens and rebuild. */\n';

/** Resolves brand.json plus one theme into a flat map of kebab-case name → value. */
async function resolveTheme(theme) {
  const sd = new StyleDictionary({
    source: [join(here, 'src/tokens/brand.json'), join(here, `src/tokens/${theme}.json`)],
    usesDtcg: true,
    log: { verbosity: 'silent' },
    platforms: { flat: { transforms: ['name/kebab'] } },
  });
  const { allTokens } = await sd.getPlatformTokens('flat');
  return Object.fromEntries(allTokens.map((token) => [token.name, String(token.$value)]));
}

const block = (selector, entries) =>
  `${selector} {\n${entries.map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}\n`;

const pick = (tokens, prefix) => Object.entries(tokens).filter(([name]) => name.startsWith(prefix));

function tokensCss(light, dark) {
  const THEMED = ['color-', 'shadow-', 'surface-'];
  const themed = (tokens) => THEMED.flatMap((prefix) => pick(tokens, prefix));
  const brand = Object.entries(light).filter(([name]) => !THEMED.some((prefix) => name.startsWith(prefix)));
  const aura = (entries) => entries.map(([name, value]) => [`--aura-${name}`, value]);
  return HEADER + block(':root', [...aura(brand), ...aura(themed(light))]) + '\n' + block('.dark', aura(themed(dark)));
}

