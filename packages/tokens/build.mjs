/**
 * The focus outline of auradata.mx on every component: focus-width of --ring, focus-offset away from
 * the element, only for the keyboard (:focus-visible). Rules as a registry item's `css` takes them.
 *
 *   - @layer base: plain elements (links, native controls) get it instead of the browser's outline.
 *   - Unlayered: stock shadcn components hide the outline (`outline-none`, a utility, which beats any
 *     base rule) and draw a 3px box-shadow ring at 50% through `focus-visible:ring-*`. Those classes
 *     are the signal: where shadcn draws a focus ring, the brand outline replaces it and the ring
 *     shadow goes. Popups, menu items and inner inputs take focus too, but without a ring class, so
 *     they keep their stock look. The ring of a field group lands on the group, as shadcn's does:
 *     `focus-within:ring-*`, an input group, a code block, a choice card (field label around a
 *     field, whose control then drops its own), and a control whose focus lands on a native input
 *     inside it (the slider thumb). `:where()` keeps the specificity at one pseudo-class, so an
 *     app's own rule can still win.
 *   - Scrolling viewports clip what lies outside them: their outline goes inside.
 *
 * Forced colors: the outline takes the system color, where the stock box-shadow ring vanished.
 */
function focusCss(tokens) {
  const width = tokens['focus-width'];
  const offset = tokens['focus-offset'];
  const outline = { outline: `${width} solid var(--ring)`, 'outline-offset': offset };
  const card = '[data-slot="field-label"]:has(> [data-slot="field"])';
  const rings = [
    `:where([class*="focus-visible:ring-"]:not([class~="focus-visible:ring-0"], ${card} *)):focus-visible`,
    ':where([class*="focus-visible:ring-"]):has(> input:focus-visible)',
    ':where([class*="focus-within:ring-"]:not([class*="focus-within:ring-0"])):has(:focus-visible)',
    ':where([data-slot="input-group"]:not([data-slot="combobox-content"] *)):has([data-slot="input-group-control"]:focus-visible)',
    ':where([data-slot="code-block"]):has(> [data-slot="code-block-content"]:focus-visible)',
    `:where(${card}):has(:focus-visible)`,
  ];
  return {
    '@layer base': {
      ':focus-visible': outline,
      // WCAG 1.4.11: the --input border of an unchecked checkbox or radio reads 1.26:1; theirs reads 3:1.
      // Only --input changes on them, so the checked, invalid and focused borders stay shadcn's.
      ':where([data-slot="checkbox"], [data-slot="radio-group-item"])': { '--input': 'var(--control-border)' },
    },
    [rings.join(',\n')]: { ...outline, '--tw-ring-shadow': '0 0 #0000' },
    ':where([data-slot$="viewport"]):focus-visible': { 'outline-offset': `-${width}` },
  };
}

/** Tailwind's stock spacing step, in rem: every size and gap of a shadcn component is a multiple of it (h-8). */
const SPACING_REM = 0.25;

/**
 * Compact density for BI screens: `data-density="compact"` on <html> or on a section scales Tailwind's --spacing by
 * density-compact, so the controls, table rows and menu items under it shrink (h-8 32px → 28px) while the type stays.
 * `data-density="normal"` gives a section inside a compact one the stock step back. In @layer base, after
 * Tailwind's theme layer, so an app's own rule still wins. Menus and dialogs open in a portal under <body>: they
 * follow <html>'s density, not their trigger's section.
 */
function densityCss(tokens) {
  const compact = Number(tokens['density-compact']);
  return {
    '@layer base': {
      '[data-density="compact"]': { '--spacing': `${SPACING_REM * compact}rem` },
      '[data-density="normal"]': { '--spacing': `${SPACING_REM}rem` },
    },
  };
}

/** Elements a printed report leaves out: app navigation, toasts, and anything marked data-print="hide". */
const PRINT_HIDDEN = [
  'nav',
  '[role="navigation"]',
  '[data-slot="sidebar"]',
  '[data-slot="sidebar-trigger"]',
  '[data-slot="sidebar-rail"]',
  // The app bar: the header that holds the sidebar trigger (its breadcrumb and actions are screen-only).
  'header:has([data-slot="sidebar-trigger"])',
  '[data-sonner-toaster]',
  '[data-print="hide"]',
];

/** Blocks a page break should not cut: table rows, figures, cards, charts, KPI cards. */
const PRINT_WHOLE = [
  'tr',
  'img',
  'svg',
  'figure',
  'pre',
  'blockquote',
  '[data-slot="card"]',
  '[data-slot="chart"]',
  '[data-slot="kpi-card"]',
  '[data-slot="alert"]',
];

/**
 * Reports on paper: printing from dark mode gives the light theme (every shadcn variable at its light value), with
 * backgrounds kept, so tints, badges and heatmap cells print as on screen; no shadows (rings, the edge of a card,
 * stay), animations or transitions;
 * no navigation; headings stay with what follows, cards, charts and rows stay whole, table headers repeat on
 * each page; scrolling tables print whole; an external link prints its address after it. `data-print="only"`
 * shows something only on paper (a printed-on date), `data-print="hide"` only on screen.
 */
function printCss(light) {
  const lightVars = Object.fromEntries(Object.entries(SHADCN).map(([name, aura]) => [`--${name}`, light[aura]]));
  return {
    '@media print': {
      // Doubled: wins over the theme's own :root and .dark blocks wherever the shadcn CLI writes them.
      ':root:root, .dark.dark': { 'color-scheme': 'light', ...lightVars },
      html: { '-webkit-print-color-adjust': 'exact', 'print-color-adjust': 'exact' },
      // Tailwind composes box-shadow from rings (the 1px edge of a card) and --tw-shadow: only the shadow goes.
      '*, ::before, ::after': {
        '--tw-shadow': '0 0 #0000 !important',
        '--tw-inset-shadow': '0 0 #0000 !important',
        'text-shadow': 'none !important',
        animation: 'none !important',
        transition: 'none !important',
      },
      [PRINT_HIDDEN.join(', ')]: { display: 'none !important' },
      '[data-slot="table-container"], [data-slot="scroll-area-viewport"]': { overflow: 'visible !important' },
      'h1, h2, h3, h4': { 'break-after': 'avoid' },
      [PRINT_WHOLE.join(', ')]: { 'break-inside': 'avoid' },
      thead: { display: 'table-header-group' },
      'p, li': { orphans: '3', widows: '3' },
      'a[href^="http"]:not([data-slot="button"])::after': {
        content: '" (" attr(href) ")"',
        'font-size': '0.875em',
        'font-weight': 'normal',
        color: 'var(--muted-foreground)',
        'overflow-wrap': 'anywhere',
      },
    },
    '@media screen': { '[data-print="only"]': { display: 'none' } },
    '@page': { margin: '16mm 14mm' },
  };
}

/** Every rule the theme adds besides its variables, merged so each at-rule appears once. */
function themeCss(tokens) {
  const merged = {};
  for (const rules of [focusCss(tokens), densityCss(tokens), printCss(tokens)]) {
    for (const [selector, body] of Object.entries(rules)) {
      merged[selector] = selector.startsWith('@') ? { ...merged[selector], ...body } : body;
    }
  }
  return merged;
}

/** CSS text of rules in the shape of a registry item's `css`: selectors and at-rules nest. */
function cssOf(rules, indent = '') {
  return Object.entries(rules)
    .map(([selector, body]) => {
      const inner = Object.entries(body).map(([key, value]) =>
        typeof value === 'object' ? cssOf({ [key]: value }, indent + '  ') : `${indent}  ${key}: ${value};\n`,
      );
      return `${indent}${selector.replaceAll('\n', `\n${indent}`)} {\n${inner.join('')}${indent}}\n`;
    })
    .join('');
}

function shadcnCss(light) {
  const entries = Object.entries(SHADCN).map(([name, aura]) => [`--${name}`, `var(--aura-${aura})`]);
  return (
    HEADER +
    "/* Import after tokens.css and shadcn's own theme, so these win. */\n" +
    block(':root, .dark', entries) +
    '\n/* The brand focus ring on every component, the compact density and print. */\n' +
    cssOf(themeCss(light))
  );
}

