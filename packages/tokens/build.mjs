/**
 * Builds the AuraData tokens for every product.
 *
 * Style Dictionary resolves the sources (brand plus one theme) and each writer
 * below turns the resolved tokens into the shape one consumer reads:
 *
 *   tokens.css    --aura-* variables, light on :root and dark on .dark
 *   shadcn.css    the shadcn semantic variables, pointing at --aura-*
 *   shadcn-theme.json  the same mapping with raw values, for a shadcn registry theme item
 *   tailwind.css  a Tailwind 4 @theme with the brand
 *   infima.css    Docusaurus (Infima) variables, light and [data-theme='dark']
 *   antd.json     antd theme tokens, light and dark (AuraData BI reads them)
 *
 * Usage: node build.mjs [--out <dir>]
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';
import StyleDictionary from 'style-dictionary';

const here = import.meta.dirname;
const { values } = parseArgs({ options: { out: { type: 'string', default: join(here, 'dist') } } });
const outDir = resolve(values.out);

const HEADER = '/* Generated by @auradata/tokens. Do not edit: change src/tokens and rebuild. */\n';

/** Resolves brand.json plus one theme into a flat map of kebab-case name → value. */
async function resolveTheme(theme) {
  const sd = new StyleDictionary({
    source: [join(here, 'src/tokens/brand.json'), join(here, `src/tokens/${theme}.json`)],
    usesDtcg: true,
    log: { verbosity: 'silent' },
    platforms: { flat: { transforms: ['name/kebab'] } },
  });
  const { allTokens } = await sd.getPlatformTokens('flat');
  return Object.fromEntries(allTokens.map((token) => [token.name, String(token.$value)]));
}

const block = (selector, entries) =>
  `${selector} {\n${entries.map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}\n`;

const pick = (tokens, prefix) => Object.entries(tokens).filter(([name]) => name.startsWith(prefix));

function tokensCss(light, dark) {
  const themed = (tokens) => [...pick(tokens, 'color-'), ...pick(tokens, 'shadow-')];
  const brand = Object.entries(light).filter(([name]) => !name.startsWith('color-') && !name.startsWith('shadow-'));
  const aura = (entries) => entries.map(([name, value]) => [`--aura-${name}`, value]);
  return HEADER + block(':root', [...aura(brand), ...aura(themed(light))]) + '\n' + block('.dark', aura(themed(dark)));
}

/** shadcn names → AuraData names. One block: the --aura-* variables already switch with .dark. */
