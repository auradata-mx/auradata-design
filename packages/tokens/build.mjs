function shadcnCss() {
  const entries = Object.entries(SHADCN).map(([name, aura]) => [`--${name}`, `var(--aura-${aura})`]);
  return HEADER + "/* Import after tokens.css and shadcn's own theme, so these win. */\n" + block(':root, .dark', entries);
}

/** shadcn variables a stock shadcn theme lacks: the registry theme item maps them into Tailwind. */
const SHADCN_EXTRA = ['destructive-foreground', 'success', 'success-foreground', 'warning', 'warning-foreground', 'info', 'info-foreground'];

/** The shadcn mapping with resolved values: the cssVars of a registry:theme item. */
function shadcnTheme(light, dark) {
  const resolved = (tokens) =>
    Object.fromEntries(Object.entries(SHADCN).map(([name, aura]) => [name, tokens[aura]]));
  return {
    theme: {
      'font-sans': light['font-sans'],
      'font-mono': light['font-mono'],
      ...Object.fromEntries(SHADCN_EXTRA.map((name) => [`color-${name}`, `var(--${name})`])),
    },
    light: resolved(light),
    dark: resolved(dark),
  };
}

function tailwindCss(light) {
  const entries = [
    ...pick(light, 'brand-').map(([name, value]) => [`--color-aura-${name.slice('brand-'.length)}`, value]),
    ...pick(light, 'chart-').map(([name, value]) => [`--color-${name}`, value]),
    ['--font-sans', light['font-sans']],
    ['--font-mono', light['font-mono']],
    ...pick(light, 'radius-').map(([name, value]) => [`--${name}`, value]),
    ['--ease-fluid', light['ease-fluid']],
  ];
  return HEADER + block('@theme', entries);
}

function infimaCss(light, dark) {
  const shades = [
    ['dark', 'black 10%'],
    ['darker', 'black 15%'],
    ['darkest', 'black 30%'],
    ['light', 'white 10%'],
    ['lighter', 'white 15%'],
    ['lightest', 'white 30%'],
  ].map(([shade, mix]) => [`--ifm-color-primary-${shade}`, `color-mix(in srgb, var(--ifm-color-primary), ${mix})`]);
  const themed = (tokens) => [
    ['--ifm-color-primary', tokens['color-primary']],
    ['--ifm-link-color', tokens['color-link']],
    ['--ifm-color-success', tokens['color-success']],
    ['--ifm-color-warning', tokens['color-warning']],
    ['--ifm-color-danger', tokens['color-error']],
    ['--ifm-background-color', tokens['color-bg-container']],
    ['--ifm-font-color-base', tokens['color-text']],
    ['--ifm-color-emphasis-300', tokens['color-border']],
  ];
  return (
    HEADER +
    block(':root', [
      ...themed(light),
      ...shades,
      ['--ifm-font-family-base', light['font-sans']],
      ['--ifm-font-family-monospace', light['font-mono']],
      ['--ifm-global-radius', light['radius-md']],
    ]) +
    '\n' +
    block("[data-theme='dark']", themed(dark))
  );
}

/** antd token names → AuraData names, the keys of THEME_DEFAULT and THEME_DARK in AuraData BI. */
const ANTD_COLORS = {
  colorPrimary: 'color-primary',
  colorLink: 'color-link',
  colorInfo: 'color-info',
  colorSuccess: 'color-success',
  colorWarning: 'color-warning',
  colorError: 'color-error',
  colorBgLayout: 'color-bg-layout',
  colorBgContainer: 'color-bg-container',
  colorBgElevated: 'color-bg-elevated',
  colorBorder: 'color-border',
  colorBorderSecondary: 'color-border-secondary',
  colorText: 'color-text',
  colorTextSecondary: 'color-text-secondary',
  colorTextTertiary: 'color-text-tertiary',
  colorFillSecondary: 'color-fill-secondary',
  colorEditorSelection: 'color-selection',
  boxShadow: 'shadow-card',
  boxShadowSecondary: 'shadow-float',
};

const px = (value) => Number.parseFloat(value);

function antdTheme(tokens, algorithm) {
  const colors = Object.fromEntries(Object.entries(ANTD_COLORS).map(([key, name]) => [key, tokens[name]]));
  return {
    token: {
      fontFamily: tokens['font-sans'],
      fontFamilyCode: tokens['font-mono'],
      borderRadius: px(tokens['radius-md']),
      borderRadiusLG: px(tokens['radius-lg']),
      borderRadiusSM: px(tokens['radius-sm']),
      motionEaseOut: tokens['ease-fluid'],
      fontSize: px(tokens['font-size-base']),
      fontSizeSM: px(tokens['font-size-sm']),
      fontSizeLG: px(tokens['font-size-lg']),
      fontSizeXL: px(tokens['font-size-xl']),
      fontSizeHeading1: px(tokens['font-size-4xl']),
      fontSizeHeading2: px(tokens['font-size-3xl']),
      fontSizeHeading3: px(tokens['font-size-2xl']),
      fontSizeHeading4: px(tokens['font-size-xl']),
      fontSizeHeading5: px(tokens['font-size-lg']),
      fontWeightStrong: Number(tokens['font-weight-strong']),
      lineHeight: Number(tokens['line-height-base']),
      zIndexPopupBase: Number(tokens['z-index-dropdown']),
      ...colors,
    },
    algorithm,
  };
}

const light = await resolveTheme('light');
const dark = await resolveTheme('dark');

mkdirSync(outDir, { recursive: true });
const files = {
  'tokens.css': tokensCss(light, dark),
  'shadcn.css': shadcnCss(),
  'shadcn-theme.json': JSON.stringify(shadcnTheme(light, dark), null, 2) + '\n',
  'tailwind.css': tailwindCss(light),
  'infima.css': infimaCss(light, dark),
  'antd.json': JSON.stringify({ light: antdTheme(light, 'default'), dark: antdTheme(dark, 'dark') }, null, 2) + '\n',
};
for (const [name, content] of Object.entries(files)) {
  writeFileSync(join(outDir, name), content);
}
console.log(`@auradata/tokens: ${Object.keys(files).length} files in ${outDir}`);
